export function t(key, language = DEFAULT_LANGUAGE, variables = {}) {
  const entry = uiStrings[key];
  const template = entry?.[normalizeLanguage(language)] ?? entry?.en ?? key;
  return Object.entries(variables).reduce((value, [name, replacement]) => {
    const token = '{' + name + '}';
    return value.replaceAll(token, String(replacement));
  }, template);
}

export function localize(value, language = DEFAULT_LANGUAGE) {
  if (normalizeLanguage(language) !== 'zh' || typeof value !== 'string') return value;
  return zhContent[value] ?? value;
}

export function hasLocalizedValue(value) {
  return typeof value !== 'string' || Object.prototype.hasOwnProperty.call(zhContent, value);
}

export function languageQueryValue(language) {
  return normalizeLanguage(language) === 'zh' ? 'zh-Hant' : 'en';
}
